Fixpoint checked_array (w : bool) (b : block) (offset step : Z) (tau : type) (vs : list val) : asrt :=
  match vs with
  | nil => Aemp
  | v :: tail => Amapsto (b, offset) tau w v ** checked_array w b (offset + step)%Z step tau tail
  end.
Fixpoint checked_cells (b : block) (offset step : Z) (tau : type) (n : nat) : list (addr * type) :=
  match n with
  | O => nil
  | S n' => ((b, offset), tau) :: checked_cells b (offset + step)%Z step tau n'
  end.
Definition checked_borrow : forall b offset step tau vs,
  checked_array true b offset step tau vs ==>
  checked_array false b offset step tau vs ** checked_array false b offset step tau vs :=
  V293_array_borrow.
Definition checked_reunite : forall b offset step tau vs,
  checked_array false b offset step tau vs ** checked_array false b offset step tau vs ==>
  checked_array true b offset step tau vs := V293_array_reunite.
