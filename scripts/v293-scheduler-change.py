def mutations(source, replace):
    def theorem_change(name, old, new):
        start = source.index('Theorem ' + name)
        end = source.index('Qed.', start) + len('Qed.')
        return source[:start] + replace(source[start:end], old, new) + source[end:]
    inverted = theorem_change('V293_OSSched_priority_comparison',
        'then Int.zero else Int.one)) /\\', 'then Int.one else Int.zero)) /\\')
    permission = replace(source,
        'V293_counter_bindings counter b ** PV (b, Int.zero) @ Tint32 |-> (Vint32 c).',
        'V293_counter_bindings counter b ** Amapsto (b, 0%Z) Tint32 false (Vint32 c).')
    add_two = theorem_change('V293_OSSched_counter_increment',
        '(frame ** V293_counter_cell counter b (Int.add c Int.one))) tid.',
        '(frame ** V293_counter_cell counter b (Int.add c (Int.repr 2)))) tid.')
    wrong_post = theorem_change('V293_OSSched_change_continuation',
        'then V293_OSSched_tail_state c else q) tid.',
        'then q else V293_OSSched_tail_state c) tid.')
    def extra_premise(premise):
        s = theorem_change('V293_OSSched_guarded_changed_prefix',
                          '  lo < 256 -> hi < 256 ->', '  ' + premise + ' -> lo < 256 -> hi < 256 ->')
        start = s.index('Theorem V293_OSSched_guarded_changed_prefix')
        return s[:start] + replace(s[start:],
            '    Hli Hlo Hhi Hr Hb Htable Hframe Hni Hnl Hnc Hspec',
            '    Hli Hextra Hlo Hhi Hr Hb Htable Hframe Hni Hnl Hnc Hspec')
    return {
        'priority_comparison_inverted_only': (inverted, 'Theorem V293_OSSched_priority_comparison'),
        'counter_write_permission_removed_only': (permission, 'Theorem V293_OSSched_counter_increment'),
        'counter_result_adds_two_only': (add_two, 'Theorem V293_OSSched_counter_increment'),
        'equal_priority_post_inverted_only': (wrong_post, 'Theorem V293_OSSched_change_continuation'),
        'counter_no_wrap_premise_added_only': (extra_premise('c <> Int.repr 4294967295'), 'Definition checked_guarded_change :'),
        'guarded_change_false_premise_added_only': (extra_premise('False'), 'Definition checked_guarded_change :'),
    }


def unit_label(rel):
    # The code and proof intentionally have the same basename. Keep their
    # command identities distinct so a success cannot overwrite a failure.
    return ('code:' if rel == CODE else '') + Path(rel).stem


def check(root, work, build, coqbin, run, loader, location):
    if (root / CODE).read_text() != EMISSION:
        raise ValueError('change Coq emission differs from checked configured change AST')
    caller = loader(root, 'v293-scheduler-caller.py')
    probe = (loader(root, 'v293-scheduler-source.py').PROBE +
             loader(root, 'v293-scheduler-internal.py').PRELUDE + caller.PROBE +
             loader(root, 'v293-scheduler-prefix.py').PROBE +
             loader(root, 'v293-scheduler-guards.py').PROBE + PROBE)
    checks = {}
    def record(label, command, cwd):
        if label in checks:
            raise ValueError('duplicate change command identity: ' + label)
        row = run('changes:' + label, command, cwd); checks[label] = row
        return row

    def compile_tree(label, replacement=None, assumptions=False):
        dest = work / ('changes_' + label)
        # Dependencies only from this run's empty-directory full build.
        shutil.copytree(build / 'certiucos', dest / 'certiucos')
        (dest / 'checks').mkdir()
        flags = ['-R', str(build / 'framework'), 'CertiOS.framework',
                 '-R', str(build / 'tactics'), 'CertiOS.tactics',
                 '-R', str(dest / 'certiucos'), 'CertiOS.certiucos',
                 '-R', str(dest / 'checks'), 'ChangesCheck']
        for rel in FILES:
            path = dest / rel
            for suffix in ['.vo', '.vos', '.vok', '.glob']:
                path.with_suffix(suffix).unlink(missing_ok=True)
            path.write_text(replacement if rel == CORE and replacement is not None else (root / rel).read_text())
            row = record(label + ':' + unit_label(rel), [coqbin + 'coqc', '-q', *flags, str(path)], dest)
            if row['exit_code']:
                return row, flags, dest
        path = dest / 'checks/Contract.v'
        path.write_text(probe + ('\n' + '\n'.join('Print Assumptions ' + r + '.' for r in ROOTS) if assumptions else ''))
        row = record(label + ':contract', [coqbin + 'coqc', '-q', *flags, str(path)], dest)
        return row, flags, dest

    row, flags, dest = compile_tree('positive', assumptions=True)
    if row['exit_code']:
        raise ValueError('changes proof/probe failed: ' + str(row))
    trust = loader(root, 'check-memory-trust.py'); assumptions = set()
    for part in row['stdout'].split('Axioms:')[1:]:
        assumptions |= set(trust.check_assumptions(part.split('Closed under the global context')[0], trust.FRAMEWORK_ALLOWED))
    if row['stdout'].count('Axioms:') + row['stdout'].count('Closed under the global context') != len(ROOTS):
        raise ValueError('missing changes root assumption output')
    row = record('coqchk', [coqbin + 'coqchk', '-silent', *flags,
        *['CertiOS.' + Path(f).with_suffix('').as_posix().replace('/', '.') for f in FILES],
        'ChangesCheck.Contract'], dest)
    if row['exit_code']:
        raise ValueError('changes coqchk failed: ' + str(row))
    for label, (mutant, declaration) in mutations((root / CORE).read_text(), caller.replace_once).items():
        row, _, _ = compile_tree(label, mutant)
        is_probe = declaration.startswith('Definition ')
        failed_source = probe if is_probe else mutant
        start = failed_source.index(declaration)
        lo = failed_source[:start].count('\n') + 1
        end = failed_source.index('\nDefinition ', start + len(declaration)) if is_probe else failed_source.index('Qed.', start)
        hi = failed_source[:end].count('\n') + 1
        match = re.search(r'line (\d+), characters', row['stderr'])
        expected_file = '/checks/Contract.v' if is_probe else '/' + CORE
        if (row['exit_code'] != 1 or not match or not lo <= int(match[1]) <= hi
                or expected_file not in row['stderr']):
            raise ValueError('changes control missed designated obligation: ' + label + ': ' + str(row))
        if checks[label + ':' + unit_label(CODE)]['exit_code'] != 0:
            raise ValueError('changes control code prerequisite failed')
        if is_probe and any(checks[label + ':' + unit_label(f)]['exit_code'] != 0 for f in FILES):
            raise ValueError('changes vacuity control prerequisite failed')
    return {'scope': SCOPE, 'coverage_credit': False, 'roots': ROOTS, 'source_location': location,
            'root_assumptions': sorted(assumptions), 'negative_controls': CONTROLS, 'normalization': NORMALIZATION}


def validate(root, checkpoint, checks, loader):
    import json
    inventory = json.loads((root / 'audit/repaired-source-inventory.json').read_text())
    expected = {'scope': SCOPE, 'coverage_credit': False, 'roots': ROOTS,
        'source_location': next(f for f in inventory['functions'] if f['name'] == 'OS_Sched'),
        'root_assumptions': checkpoint['root_assumptions'], 'negative_controls': CONTROLS, 'normalization': NORMALIZATION}
    if checkpoint != expected:
        raise ValueError('changes checkpoint scope/roots/source/controls differ')
    if not set(checkpoint['root_assumptions']) <= loader(root, 'check-memory-trust.py').FRAMEWORK_ALLOWED:
        raise ValueError('unexpected changes root assumptions')
    for key in ['positive:' + unit_label(f) for f in FILES] + ['positive:contract', 'coqchk']:
        if checks['changes:' + key]['exit_code'] != 0:
            raise ValueError('changes checkpoint positive check failed')
    for label in CONTROLS:
        if checks['changes:' + label + ':' + unit_label(CODE)]['exit_code'] != 0:
            raise ValueError('changes control code prerequisite missing')
        is_probe = label in {'guarded_change_false_premise_added_only', 'counter_no_wrap_premise_added_only'}
        if is_probe and any(checks['changes:' + label + ':' + unit_label(f)]['exit_code'] != 0 for f in FILES):
            raise ValueError('changes control prerequisite missing')
        key = label + (':contract' if is_probe else ':' + Path(CORE).stem)
        if checks['changes:' + key]['exit_code'] != 1:
            raise ValueError('changes designated control missing')
